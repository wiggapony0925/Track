-- ─────────────────────────────────────────────────────────────────────────────
-- Track analytics layer: TikTok-grade behavioral telemetry
--
-- Design goals
-- • Backend (service role) is the SOLE writer.  iOS never POSTs directly.
-- • Per-user reads via RLS using auth.uid() — users can only see their own data.
-- • Tables denormalised for cheap funnels & cohorts (no joins on hot paths).
-- • All timestamps UTC, all jsonb fields default '{}'::jsonb / '[]'::jsonb.
-- • Idempotent: safe to re-run if Supabase ever rolls back.
--
-- Identity model
-- • uuid user_id → references auth.users(id)  (mirrors profiles/favorites).
-- • Apple-sub text identities (engine_*) are kept as-is and not touched here.
--
-- Cleanup
-- • Removes the 1 smoke-test feedback row from the previous migration.
-- ─────────────────────────────────────────────────────────────────────────────

-- 0. Smoke-test cleanup ------------------------------------------------------

delete from public.metromind_feedback
 where user_prompt = 'hi'
   and assistant_text = 'hi back';


-- 1. Helper: timestamptz updated_at trigger (idempotent) ---------------------

create or replace function public.analytics_set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;


-- 2. user_sessions ───────────────────────────────────────────────────────────
-- One row per foreground session (≤ 30 s gap merges into prior session).

create table if not exists public.user_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  started_at timestamptz not null default timezone('utc', now()),
  ended_at timestamptz,
  last_active_at timestamptz not null default timezone('utc', now()),
  app_version text,
  build text,
  os_version text,
  device_model text,
  locale text,
  timezone text,
  network_type text,                         -- 'wifi' | 'cellular' | 'none'
  foreground_seconds integer not null default 0,
  screens_viewed integer not null default 0,
  events_count integer not null default 0,
  entry_screen text,
  entry_source text,                         -- 'cold' | 'warm' | 'push' | 'shortcut' | 'widget'
  push_notification_id text,
  initial_lat double precision,
  initial_lon double precision,
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_user_sessions_user_started
  on public.user_sessions (user_id, started_at desc);
create index if not exists idx_user_sessions_active
  on public.user_sessions (user_id, last_active_at desc) where ended_at is null;

drop trigger if exists set_user_sessions_updated_at on public.user_sessions;
create trigger set_user_sessions_updated_at
  before update on public.user_sessions
  for each row execute function public.analytics_set_updated_at();


