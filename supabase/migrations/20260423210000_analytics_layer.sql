  properties jsonb not null default '{}'::jsonb,
  screen text,
  occurred_at timestamptz not null default timezone('utc', now()),
  app_version text,
  os_version text,
  device_model text,
  network_type text,
  lat double precision,
  lon double precision,
  ingested_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_analytics_events_user_time
  on public.analytics_events (user_id, occurred_at desc);
create index if not exists idx_analytics_events_name_time
  on public.analytics_events (event_name, occurred_at desc);
create index if not exists idx_analytics_events_session
  on public.analytics_events (session_id, occurred_at desc);
create index if not exists idx_analytics_events_props_gin
  on public.analytics_events using gin (properties);


