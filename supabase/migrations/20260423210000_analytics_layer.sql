-- ─────────────────────────────────────────────────────────────────────────────
-- 12. RLS — analytics tables: per-user SELECT, service-role-only writes
-- ─────────────────────────────────────────────────────────────────────────────

do $$
declare
  t text;
begin
  for t in select unnest(array[
    'user_sessions','analytics_events','screen_views','search_queries',
    'route_engagements','map_interactions','error_events',
    'performance_metrics','notification_events','feature_flag_exposures'
  ]) loop
    execute format('alter table public.%I enable row level security;', t);
    execute format('drop policy if exists "%s_owner_read" on public.%I;', t, t);
    execute format($p$create policy "%s_owner_read" on public.%I
                       for select to authenticated
                       using (auth.uid() = user_id);$p$, t, t);
  end loop;
end $$;


-- ─────────────────────────────────────────────────────────────────────────────
-- 13. RLS audit — ensure every existing public table has RLS enabled
--     (service-role bypasses RLS automatically; this just slams the door
--     on anyone with the anon key trying to read raw rows).
-- ─────────────────────────────────────────────────────────────────────────────

do $$
declare
  t text;
begin
  for t in
    select c.relname
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and c.relkind = 'r'
       and c.relrowsecurity = false
  loop
    execute format('alter table public.%I enable row level security;', t);
    raise notice 'enabled RLS on public.%', t;
  end loop;
end $$;


-- ─────────────────────────────────────────────────────────────────────────────
-- 14. Per-user SELECT policies for uuid-keyed user-owned tables that didn't
--     have one.  (We can't add auth.uid() policies to engine_* tables because
--     they store text Apple-sub identities, not uuids — those remain
--     service-role-only, which is correct given iOS goes through the backend.)
-- ─────────────────────────────────────────────────────────────────────────────

do $$
declare
  t text;
begin
  for t in select unnest(array[
    'profiles','favorites','schedules','user_settings',
    'commute_patterns','route_interactions','trip_configurations',
    'metromind_threads','metromind_feedback'
  ]) loop
    -- profiles uses 'id' as the FK to auth.users, the rest use 'user_id'
    if t = 'profiles' then
      execute format('drop policy if exists "%s_owner_read" on public.%I;', t, t);
      execute format($p$create policy "%s_owner_read" on public.%I
                         for select to authenticated
                         using (auth.uid() = id);$p$, t, t);
    elsif t = 'metromind_threads' or t = 'metromind_feedback' then
      -- These tables don't currently carry a user_id column.
      -- Keep them service-role-only; backend filters by thread_id.
      continue;
    else
      execute format('drop policy if exists "%s_owner_read" on public.%I;', t, t);
      execute format($p$create policy "%s_owner_read" on public.%I
                         for select to authenticated
                         using (auth.uid() = user_id);$p$, t, t);
    end if;
  end loop;
end $$;
