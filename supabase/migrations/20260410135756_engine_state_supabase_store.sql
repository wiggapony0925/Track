create or replace function public.engine_trim_recent_trips(
  p_user_id text,
  p_keep_rows integer default 100
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted integer := 0;
begin
  delete from public.engine_recent_trips
  where user_id = p_user_id
    and id in (
      select id
      from public.engine_recent_trips
      where user_id = p_user_id
      order by requested_at desc, id desc
      offset greatest(p_keep_rows, 0)
    );

  get diagnostics v_deleted = row_count;
  return v_deleted;
end;
$$;

create or replace function public.engine_recent_destinations(
  p_user_id text,
  p_limit integer default 20
)
returns table (
  label text,
  lat double precision,
  lon double precision,
  trip_count bigint,
  last_used_at bigint
)
language sql
stable
security definer
set search_path = public
as $$
  with grouped as (
    select
      destination_label as label,
      round(destination_lat::numeric, 4) as rounded_lat,
      round(destination_lon::numeric, 4) as rounded_lon,
      avg(destination_lat)::double precision as lat,
      avg(destination_lon)::double precision as lon,
      count(*)::bigint as trip_count,
      max(requested_at) as last_used_at
    from public.engine_recent_trips
    where user_id = p_user_id
    group by destination_label,
             round(destination_lat::numeric, 4),
             round(destination_lon::numeric, 4)
  )
  select
    grouped.label,
    grouped.lat,
    grouped.lon,
    grouped.trip_count,
    extract(epoch from grouped.last_used_at)::bigint as last_used_at
  from grouped
  order by grouped.trip_count desc, grouped.last_used_at desc
  limit greatest(p_limit, 0);
$$;

