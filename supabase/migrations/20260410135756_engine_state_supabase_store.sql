create or replace function public.engine_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create table if not exists public.engine_saved_places (
  id bigint generated by default as identity primary key,
  user_id text not null,
  label text not null check (char_length(trim(label)) > 0),
  kind text not null check (char_length(trim(kind)) > 0),
  lat double precision not null,
  lon double precision not null,
  address text,
  icon text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  last_used_at timestamptz
);

create index if not exists idx_engine_saved_places_user
  on public.engine_saved_places (user_id, kind, updated_at desc, label);

create table if not exists public.engine_saved_trips (
  id bigint generated by default as identity primary key,
  user_id text not null,
  name text not null check (char_length(trim(name)) > 0),
  origin_label text not null check (char_length(trim(origin_label)) > 0),
  origin_lat double precision not null,
  origin_lon double precision not null,
  destination_label text not null check (char_length(trim(destination_label)) > 0),
  destination_lat double precision not null,
  destination_lon double precision not null,
  preferred_departure_hour smallint check (
    preferred_departure_hour is null
    or (preferred_departure_hour between 0 and 23)
  ),
  preferred_arrival_hour smallint check (
    preferred_arrival_hour is null
    or (preferred_arrival_hour between 0 and 23)
  ),
  preferred_modes jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  last_used_at timestamptz
